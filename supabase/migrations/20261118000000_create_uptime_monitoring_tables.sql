create table if not exists public.monitors (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  url text not null,
  monitor_type text not null default 'HTTP' check (monitor_type in ('HTTP','PING','PORT')),
  interval_seconds integer not null default 300 check (interval_seconds between 60 and 86400),
  status text not null default 'up' check (status in ('up','down','paused')),
  response_ms integer,
  last_check_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.monitor_checks (
  id bigint generated by default as identity primary key,
  monitor_id bigint not null references public.monitors(id) on delete cascade,
  result_status text not null check (result_status in ('up','down')),
  status_code integer,
  response_ms integer,
  error_message text,
  checked_at timestamptz not null default now()
);

create index if not exists monitors_status_idx on public.monitors(status);
create index if not exists monitor_checks_monitor_time_idx on public.monitor_checks(monitor_id, checked_at desc);

alter table public.monitors enable row level security;
alter table public.monitor_checks enable row level security;

drop policy if exists monitors_public_select on public.monitors;
drop policy if exists monitors_public_insert on public.monitors;
drop policy if exists monitors_public_update on public.monitors;
drop policy if exists monitors_public_delete on public.monitors;
drop policy if exists monitor_checks_public_select on public.monitor_checks;
drop policy if exists monitor_checks_public_insert on public.monitor_checks;

create policy monitors_public_select on public.monitors for select to anon, authenticated using (true);
create policy monitors_public_insert on public.monitors for insert to anon, authenticated with check (true);
create policy monitors_public_update on public.monitors for update to anon, authenticated using (true) with check (true);
create policy monitors_public_delete on public.monitors for delete to anon, authenticated using (true);
create policy monitor_checks_public_select on public.monitor_checks for select to anon, authenticated using (true);
create policy monitor_checks_public_insert on public.monitor_checks for insert to anon, authenticated with check (true);

create or replace function public.set_monitors_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists monitors_updated_at on public.monitors;
create trigger monitors_updated_at before update on public.monitors for each row execute function public.set_monitors_updated_at();
