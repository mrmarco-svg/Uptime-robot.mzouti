-- MZOUTI Uptime: subscriptions, manual payment review and incident history.
-- Additive migration: existing monitors and checks are preserved.
create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan_code text not null default 'free' check (plan_code in ('free','starter','pro','business')),
  status text not null default 'active' check (status in ('active','expired','cancelled')),
  current_period_start timestamptz,
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null check (provider in ('natcash','meru')),
  plan_code text not null check (plan_code in ('starter','pro','business')),
  billing_period text not null check (billing_period in ('monthly','annual')),
  amount numeric(12,2) not null check (amount > 0),
  currency text not null default 'HTG' check (currency in ('HTG','USD')),
  reference text not null check (char_length(reference) between 1 and 160),
  proof_url text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists payment_requests_user_created_idx on public.payment_requests(user_id, created_at desc);
create index if not exists payment_requests_pending_idx on public.payment_requests(status, created_at);

create table if not exists public.monitor_incidents (
  id bigint generated by default as identity primary key,
  monitor_id bigint not null references public.monitors(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  started_at timestamptz not null default now(),
  resolved_at timestamptz,
  cause text,
  created_at timestamptz not null default now()
);
create index if not exists monitor_incidents_user_started_idx on public.monitor_incidents(user_id, started_at desc);
create unique index if not exists monitor_incidents_one_open_per_monitor_idx on public.monitor_incidents(monitor_id) where resolved_at is null;

alter table public.subscriptions enable row level security;
alter table public.payment_requests enable row level security;
alter table public.monitor_incidents enable row level security;

drop policy if exists subscriptions_select_own on public.subscriptions;
create policy subscriptions_select_own on public.subscriptions for select to authenticated using (user_id = auth.uid());
drop policy if exists payment_requests_select_own on public.payment_requests;
create policy payment_requests_select_own on public.payment_requests for select to authenticated using (user_id = auth.uid());
drop policy if exists payment_requests_insert_own on public.payment_requests;
create policy payment_requests_insert_own on public.payment_requests for insert to authenticated with check (user_id = auth.uid() and status = 'pending' and reviewed_by is null and reviewed_at is null);
drop policy if exists monitor_incidents_select_own on public.monitor_incidents;
create policy monitor_incidents_select_own on public.monitor_incidents for select to authenticated using (user_id = auth.uid());

-- Record each transition into and out of the down state, without client-side writes.
create or replace function public.track_monitor_incident()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'down' and old.status is distinct from 'down' then
    insert into public.monitor_incidents(monitor_id, user_id, cause)
    values (new.id, new.user_id, 'Le contrôle du moniteur a échoué.')
    on conflict (monitor_id) where resolved_at is null do nothing;
  elsif new.status in ('up','paused') and old.status = 'down' then
    update public.monitor_incidents
       set resolved_at = coalesce(new.last_check_at, now())
     where monitor_id = new.id and resolved_at is null;
  end if;
  return new;
end;
$$;
drop trigger if exists monitors_track_incidents on public.monitors;
create trigger monitors_track_incidents
after update of status on public.monitors
for each row execute function public.track_monitor_incident();

-- Seed the free subscription lazily through the trusted server path.

-- Atomic review + activation; only the server's service_role may execute this function.
create or replace function public.admin_review_payment_request(
  p_payment_id bigint,
  p_status text,
  p_note text,
  p_reviewer uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  payment_row public.payment_requests%rowtype;
  period_end timestamptz;
begin
  if p_status not in ('approved','rejected') then
    raise exception 'Invalid payment decision';
  end if;
  update public.payment_requests
     set status = p_status,
         admin_note = nullif(left(coalesce(p_note,''),500),''),
         reviewed_by = p_reviewer,
         reviewed_at = now()
   where id = p_payment_id and status = 'pending'
   returning * into payment_row;
  if not found then
    raise exception 'Payment request not found or already reviewed';
  end if;
  if p_status = 'approved' then
    period_end := case when payment_row.billing_period = 'annual'
      then now() + interval '1 year' else now() + interval '1 month' end;
    insert into public.subscriptions(user_id,plan_code,status,current_period_start,current_period_end,updated_at)
    values (payment_row.user_id,payment_row.plan_code,'active',now(),period_end,now())
    on conflict (user_id) do update set
      plan_code = excluded.plan_code,
      status = 'active',
      current_period_start = excluded.current_period_start,
      current_period_end = excluded.current_period_end,
      updated_at = excluded.updated_at;
  end if;
end;
$$;
revoke all on function public.admin_review_payment_request(bigint,text,text,uuid) from public, anon, authenticated;
grant execute on function public.admin_review_payment_request(bigint,text,text,uuid) to service_role;
